BEGIN;

CREATE SCHEMA IF NOT EXISTS crm;

CREATE TABLE IF NOT EXISTS crm.customers (
    source_row_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id VARCHAR(50),
    first_name VARCHAR(100),
    last_name VARCHAR(100),
    email VARCHAR(320),
    phone VARCHAR(30),
    country_code VARCHAR(10),
    status VARCHAR(20),
    created_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS ix_crm_customers_updated_at
    ON crm.customers (updated_at, source_row_id);
CREATE INDEX IF NOT EXISTS ix_crm_customers_customer_id
    ON crm.customers (customer_id, updated_at DESC);

COMMIT;
